const BY_CODE = new Map(US_STATES.map((s) => [s.code, s]));
const BY_NAME = new Map(US_STATES.map((s) => [s.name.toLowerCase(), s]));

/**
 * Resolve "Florida", " florida ", "FL", "fl." → the Florida entry. Returns
 * null for anything that isn't unambiguously one state — callers must treat
 * null as "jurisdiction not established", never as a default state.
 */
export function normalizeUsState(input: unknown): UsState | null {
  if (typeof input !== "string") return null;
  const cleaned = input.trim().replace(/\.+$/, "");
  if (!cleaned) return null;
  return BY_CODE.get(cleaned.toUpperCase()) ?? BY_NAME.get(cleaned.toLowerCase()) ?? null;
}
