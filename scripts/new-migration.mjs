#!/usr/bin/env node
/**
 * Create a migration for BOTH database engines from the current
 * prisma/schema.prisma, without the interactive `prisma migrate dev` flow:
 *
 *   npm run db:migration:new -- add_something
 *
 * SQLite (dev/test)
 *   Diffs prisma/migrations against the schema using a throwaway shadow
 *   database in the OS temp directory (never inside the repo, so file-sync
 *   tools can't lock it) → prisma/migrations/<timestamp>_<name>/migration.sql
 *
 * PostgreSQL (production)
 *   Diffs the committed prisma/postgres/schema.prisma (the model as of the
 *   last migration) against the newly generated one. Schema-to-schema, so no
 *   running Postgres is needed → prisma/postgres/migrations/<timestamp>_<name>/
 *   migration.sql, then the committed Postgres schema is updated to match.
 *
 * Neither database is touched. Apply with `npm run db:migrate` (which targets
 * whichever engine DATABASE_URL points at). CI applies the Postgres
 * migrations to a real PostgreSQL server and checks for drift.
 */
import { execSync } from "node:child_process";
import { existsSync, mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import path from "node:path";
import { toPostgresSchema } from "./sync-postgres-schema.mjs";

const name = (process.argv[2] ?? "").replace(/[^a-z0-9_]/gi, "_").toLowerCase();
if (!name) {
  console.error("Usage: npm run db:migration:new -- <migration_name>");
  process.exit(1);
}

const SQLITE_SCHEMA = path.join("prisma", "schema.prisma");
const PG_DIR = path.join("prisma", "postgres");
const PG_SCHEMA = path.join(PG_DIR, "schema.prisma");
const stamp = new Date().toISOString().replace(/[-:T]/g, "").slice(0, 14);
const scratch = mkdtempSync(path.join(tmpdir(), "bureauos-migration-"));
const q = (p) => `"${p.replace(/\\/g, "/")}"`;

function diff(args) {
  // Every part of the command is static or a quoted path this script created.
  const sql = execSync(`npx prisma migrate diff ${args} --script`, {
    encoding: "utf8",
    stdio: ["ignore", "pipe", "pipe"],
  });
  return !sql.trim() || /empty migration/i.test(sql) ? "" : sql;
}

function write(dir, sql) {
  mkdirSync(dir, { recursive: true });
  writeFileSync(path.join(dir, "migration.sql"), sql, "utf8");
  console.log(`\nWrote ${path.join(dir, "migration.sql")}:\n\n${sql}`);
}

try {
  /* ------------------------------ SQLite ------------------------------ */
  const shadowUrl = `file:${path.join(scratch, "shadow.db").replace(/\\/g, "/")}`;
  const sqliteSql = diff(
    `--from-migrations ${q(path.join("prisma", "migrations"))} --to-schema-datamodel ${q(SQLITE_SCHEMA)} --shadow-database-url "${shadowUrl}"`,
  );
  if (sqliteSql) write(path.join("prisma", "migrations", `${stamp}_${name}`), sqliteSql);
  else console.log("SQLite: schema and migrations already in sync.");

  /* ---------------------------- PostgreSQL ---------------------------- */
  const nextSchema = toPostgresSchema(readFileSync(SQLITE_SCHEMA, "utf8"));
  const nextPath = path.join(scratch, "next.prisma");
  writeFileSync(nextPath, nextSchema, "utf8");

  const from = existsSync(PG_SCHEMA) ? `--from-schema-datamodel ${q(PG_SCHEMA)}` : "--from-empty";
  const pgSql = diff(`${from} --to-schema-datamodel ${q(nextPath)}`);
  if (pgSql) {
    write(path.join(PG_DIR, "migrations", `${stamp}_${name}`), pgSql);
    const lock = path.join(PG_DIR, "migrations", "migration_lock.toml");
    if (!existsSync(lock)) {
      writeFileSync(
        lock,
        '# Please do not edit this file manually\n# It should be added in your version-control system (e.g., Git)\nprovider = "postgresql"\n',
        "utf8",
      );
    }
  } else {
    console.log("PostgreSQL: schema and migrations already in sync.");
  }
  mkdirSync(PG_DIR, { recursive: true });
  writeFileSync(PG_SCHEMA, nextSchema, "utf8");
} catch (err) {
  console.error(String(err.stderr ?? err.message).slice(0, 4000));
  process.exitCode = 1;
} finally {
  try {
    rmSync(scratch, { recursive: true, force: true });
  } catch {
    // best effort
  }
}
